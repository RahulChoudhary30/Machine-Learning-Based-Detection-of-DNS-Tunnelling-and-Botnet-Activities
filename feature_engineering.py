import pandas as pd
import numpy as np
from src.utils import setup_logger

logger = setup_logger()

def engineer_features(df, config):
    """
    Engineers new features and prepares the dataset.
    """
    logger.info("Starting feature engineering...")
    df_engineered = df.copy()
    
    # Fill any null values for critical calculations
    df_engineered['dur'] = df_engineered['dur'].replace(0, 0.0001) # Avoid division by zero
    df_engineered['tot_pkts'] = df_engineered['tot_pkts'].replace(0, 0.0001) # Avoid division by zero
    
    # Derived Behavioral Features
    logger.info("Creating derived features: bytes_per_sec, packets_per_sec, bytes_per_packet...")
    df_engineered['bytes_per_sec'] = df_engineered['tot_bytes'] / df_engineered['dur']
    df_engineered['packets_per_sec'] = df_engineered['tot_pkts'] / df_engineered['dur']
    df_engineered['bytes_per_packet'] = df_engineered['tot_bytes'] / df_engineered['tot_pkts']
    
    # Add newly derived features to the numerical config list dynamically
    if 'bytes_per_sec' not in config['features']['numerical']:
        config['features']['numerical'].extend(['bytes_per_sec', 'packets_per_sec', 'bytes_per_packet'])
        
    # Later integration: Entropy based for DNS
    # if 'domain' in df_engineered.columns:
    #     df_engineered['domain_entropy'] = df_engineered['domain'].apply(calculate_entropy)
    
    # Handle infinities generated by division
    df_engineered.replace([np.inf, -np.inf], np.nan, inplace=True)
    
    return df_engineered
